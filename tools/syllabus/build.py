"""Turns the eMove course programmes (the .txt files published at emoveacademy.com/course-content/<slug>.txt)
into src/data-syllabus.js, the syllabus shown in each course hub of the platform.

Run it again when eMove updates a programme: download the new .txt into this folder and `python3 tools/syllabus/build.py`.
"""
import json, pathlib, re

here = pathlib.Path(__file__).parent
FILES = {"game-on": "game-on", "ai-teacher": "ai-teachers-360-from-zero-to-hero", "think": "think",
         "shine": "every-student-can-shine", "outside": "outside-the-box", "happy": "the-happy-teacher"}
PART = re.compile(r"^(\S{1,2}) · (.+)$")
DAY = re.compile(r"^DAY (\d) · (.+)$")


def lines(s):
    return [l.strip() for l in s.split("\n") if l.strip()]


def section(ls):
    return {"t": ls[0], "lines": ls[1:]}


def day(ls):
    """DAY n · TITLE / subtitle / intro… / We explore: / * topics / Daily (or Final) challenge: / text…"""
    m = DAY.match(ls[0])
    d = {"n": int(m.group(1)), "title": m.group(2).title(), "sub": ls[1], "intro": [], "topics": [], "notes": [], "challenge": [], "final": False}
    mode = "intro"
    for l in ls[2:]:
        if l == "We explore:" or l.startswith("Participants explore how to design"):
            if l != "We explore:":
                d["intro"].append(l)
            mode = "topics"
        elif l in ("Daily challenge:", "Final challenge:"):
            d["final"] = l.startswith("Final")
            mode = "challenge"
        elif mode == "topics" and l.startswith("* "):
            d["topics"].append(l[2:])
        elif mode == "topics":
            d["notes"].append(l)
        else:
            d[mode].append(l)
    return d


def parse(text):
    secs = [lines(s) for s in text.split("⸻")]
    secs = [s for s in secs if s]
    c = {"hook": secs[0][2:], "why": [], "approach": None, "days": [], "ideas": [], "method": None, "toolkit": [], "outcomes": [], "who": [], "takeHome": [], "format": [], "closing": secs[-1]}
    i = 1
    while i < len(secs) - 1:
        s = secs[i]
        head = s[0]
        if head == "WHY THIS COURSE?":
            c["why"] = s[1:]
        elif head.startswith("THE ") and head.endswith(" APPROACH"):
            parts, intro, cur = [], [], None
            for l in s[1:]:
                m = PART.match(l)
                if m and l.upper() == l:
                    cur = {"k": m.group(1), "t": m.group(2), "lines": []}
                    parts.append(cur)
                elif cur:
                    cur["lines"].append(l)
                else:
                    intro.append(l)
            c["approach"] = {"t": head.title().replace("Game", "GAME").replace("Shine", "SHINE").replace("Open", "OPEN").replace("Think", "THINK").replace("Happy", "HAPPY").replace("360º", "360º"), "intro": intro, "parts": parts}
        elif PART.match(head) and head.upper() == head and c["approach"] and not c["days"]:
            m = PART.match(head)
            c["approach"]["parts"].append({"k": m.group(1), "t": m.group(2), "lines": s[1:]})
        elif head.startswith("5 DAYS") or DAY.match(head):
            ls = s[1:] if head.startswith("5 DAYS") else s
            if head.startswith("5 DAYS"):
                c["daysTitle"] = head.capitalize()
            c["days"].append(day(ls))
        elif head.startswith("YOU WON") or head.startswith("YOU WON’T"):
            c["method"] = section(s)
        elif "TOOLKIT" in head:
            c["toolkit"] = [l[2:] for l in s if l.startswith("* ")]
        elif head == "LEARNING OUTCOMES":
            c["outcomes"] = [l[2:] for l in s if l.startswith("* ")]
        elif head == "WHO IS THIS COURSE FOR?":
            c["who"] = s[1:]
        elif head == "WHAT WILL YOU TAKE HOME?":
            c["takeHome"] = s[1:]
        elif head == "COURSE FORMAT":
            c["format"] = s[1:]
        else:
            c["ideas"].append(section(s))
        i += 1
    assert len(c["days"]) == 5, len(c["days"])
    return c


out = {}
for cid, slug in FILES.items():
    out[cid] = parse((here / f"{slug}.txt").read_text())
    out[cid]["source"] = f"https://www.emoveacademy.com/course-content/{slug}.txt"
js = ("/* ============ Syllabus of each eMove course, generated by tools/syllabus/build.py from the programmes on emoveacademy.com.\n"
      "   Do not edit by hand: update the .txt files in tools/syllabus/ and run the script again. ============ */\n"
      "const SYLLABUS = " + json.dumps(out, ensure_ascii=False, indent=1) + ";\n")
(here.parent.parent / "src" / "data-syllabus.js").write_text(js)
for k, v in out.items():
    print(k, "days", [d["title"] for d in v["days"]], "parts", len(v["approach"]["parts"]) if v["approach"] else 0, "ideas", [x["t"] for x in v["ideas"]], "tools", len(v["toolkit"]), "out", len(v["outcomes"]))
